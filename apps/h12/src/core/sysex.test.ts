import { describe, expect, it } from "vitest";
import {
  checksum, decodeByte, decodeInt16, decodeWord, encodeWord, parseAnswer, readSetting, readStatus, writeSetting,
} from "./sysex";

// The examples in CME's MIDI implementation for the H12MIDI Pro.
describe("requests", () => {
  it("builds the serial and firmware status request", () => {
    expect(readStatus(0x00)).toEqual([0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x01, 0x00, 0x01, 0xf7]);
  });

  it("adds the index to a status request that has one", () => {
    expect(readStatus(0x02, 0)).toEqual([0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x01, 0x02, 0x00, 0x03, 0xf7]);
  });

  it("builds setting reads", () => {
    expect(readSetting({ setting: 0x04, index: 0 }, 1)).toEqual([0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x02, 0x04, 0x01, 0x00, 0x07, 0xf7]);
    expect(readSetting({ setting: 0x03, index: 0 }, 6)).toEqual([0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x02, 0x03, 0x06, 0x00, 0x0b, 0xf7]);
  });

  it("builds CME's routing write example (input 0 to MIDI Outs 1–6)", () => {
    expect(writeSetting({ setting: 0x00, index: 0 }, [0x3f000000])).toEqual(
      [0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x03, 0x00, 0x01, 0x00, 0x00, 0x00, 0x00, 0x40, 0x1f, 0x63, 0xf7]);
  });

  it("builds a six-word mapper write", () => {
    const d = writeSetting({ setting: 0x03, index: 18 }, [1, 2, 3, 4, 5, 6]);
    expect(d.slice(6, 10)).toEqual([0x03, 0x03, 0x06, 18]);
    expect(d).toHaveLength(10 + 6 * 5 + 2);
  });

  it("keeps the low 7 bits of the checksum", () => {
    expect(checksum([0x7f, 0x02])).toBe(0x01);
  });
});

describe("encodings", () => {
  it("round-trips a word", () => {
    expect(encodeWord(0x12345678)).toEqual([0x08, 0x67, 0x0a, 0x0d, 0x09]);
    expect(decodeWord([0x08, 0x67, 0x0a, 0x0d, 0x09], 0)).toBe(0x12345678);
    expect(decodeWord(encodeWord(0xffffffff), 0)).toBe(0xffffffff);
  });

  it("decodes a byte and an Int16", () => {
    expect(decodeByte([0x05, 0x0a], 0)).toBe(0xa5);
    expect(decodeInt16([0x00, 0x0d, 0x09], 0)).toBe(0x1234);
  });
});

describe("parseAnswer", () => {
  it("reads the preset-changed example", () => {
    const d = [0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x42, 0x04, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x40, 0x08, 0xf7];
    expect(parseAnswer(d)).toEqual({ kind: "answer", command: 0x02, id: 0x04, bytes: d });
  });

  it("ignores the flag bits above the command (the H12 on firmware 4.7 sends 0x51)", () => {
    const body = [0x51, 0x02, 0x06, 0x00, 0x00, 0x30, 0x08, 0x00, 0x00];
    const d = [0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, ...body, 0x11, 0xf7]; // captured from the hub
    expect(parseAnswer(d)).toMatchObject({ kind: "answer", command: 0x01, id: 0x02 });
  });

  it("reads an error answer", () => {
    const d = [0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x41, 0x7f, (0x41 + 0x7f) & 0x7f, 0xf7];
    expect(parseAnswer(d)).toEqual({ kind: "error", command: 0x01, code: 0x7f, message: "unknown command or parameter" });
  });

  it("reports an answer whose checksum is wrong", () => {
    const d = [0xf0, 0x00, 0x20, 0x63, 0x0f, 0x26, 0x42, 0x04, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x40, 0x09, 0xf7];
    expect(parseAnswer(d)?.kind).toBe("corrupt");
  });

  it("ignores requests, other products and other SysEx", () => {
    expect(parseAnswer(readStatus(0))).toBeUndefined();
    expect(parseAnswer([0xf0, 0x00, 0x20, 0x63, 0x0f, 0x27, 0x41, 0x00, 0x41, 0xf7])).toBeUndefined();
    expect(parseAnswer([0xf0, 0x7e, 0x7f, 0x06, 0x01, 0xf7])).toBeUndefined();
  });
});
