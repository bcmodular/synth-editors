// Generator: the agreed effect designs (docs/sp404-mockups/2-fx-designs.html) → apps/sp404/src/fx/fxLayout.ts.
// Runs the mockup's effect table (not its rendering) and keeps, per effect, its category and how each parameter is
// controlled, so the modules follow the mockup without retyping 46 effects.
// Usage: node apps/sp404/scripts/gen-fx-layout.mjs docs/sp404-mockups/2-fx-designs.html apps/sp404/src/fx/fxLayout.ts
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const [mockup, out] = process.argv.slice(2);
const lines = readFileSync(mockup, "utf8").split("\n");
const start = lines.findIndex((l) => l.startsWith("<script>")) + 1;
const end = lines.findIndex((l) => l.startsWith("// ---------------- rendering"));
const ctx = { Math };
vm.createContext(ctx);
vm.runInContext(`${lines.slice(start, end).join("\n")}\n;globalThis.__E = E; globalThis.__CATS = CATS;`, ctx);

// How a parameter is shown: a knob unless the mockup gives it a control of its own.
const kind = (p) => {
  if (p.sync) return "sync";
  if (p.t === "k") return "knob";
  return p.ui ?? "seg";
};
const syncKind = (p) => (p.sl && p.sl.ui ? p.sl.ui : undefined);

const effects = ctx.__E.map((e, i) => {
  const controls = e.p.map((p) => {
    const fields = [`kind: "${kind(p)}"`];
    if (syncKind(p)) fields.push(`synced: "${syncKind(p)}"`);
    if (kind(p) === "big") fields.push(`label: ${JSON.stringify(p.n)}`); // the device's ON/OFF gets the design's name
    return `{ ${fields.join(", ")} }`;
  });
  const extra = [
    e.extra === "kill" ? "kill: true" : "",
    e.readouts ? `readouts: [${e.readouts.join(", ")}]` : "",
    e.d ? `start: [${e.d.join(", ")}]` : "",
  ].filter(Boolean);
  return `  // ${i + 1} ${e.n}
  { name: ${JSON.stringify(e.n)}, category: ${JSON.stringify(ctx.__CATS[e.cat])},
    controls: [${controls.join(", ")}],${extra.length ? `\n    ${extra.join(", ")},` : ""} },`;
});

writeFileSync(out, `// Generated by scripts/gen-fx-layout.mjs from docs/sp404-mockups/2-fx-designs.html (the agreed designs).
// Per effect, in effect-id order: its category and how each parameter is controlled in the module.

import type { FxLayout } from "./layoutTypes";

export const FX_LAYOUT: readonly FxLayout[] = [
${effects.join("\n")}
];
`);
console.log(`Wrote ${effects.length} effect layouts to ${out}`);
